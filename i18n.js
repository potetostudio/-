// Only explicitly marked application UI is localized. User content and iframe
// documents are deliberately excluded. No translation service is contacted.
var uiLanguage = 'ja';
try {
  var savedLanguage = localStorage.getItem('pt_language');
  if (savedLanguage === 'en' || savedLanguage === 'ja') uiLanguage = savedLanguage;
} catch (e) { /* Storage may be disabled; switching still works for this session. */ }
var uiTextBindings = new Map();

function t(japanese) {
  return uiLanguage === 'en' && Object.prototype.hasOwnProperty.call(UI_EN, japanese)
    ? UI_EN[japanese] : japanese;
}

// Keep a source expression for transient UI labels so they can change language
// without rebuilding an editor, resetting a form, or restarting a request.
function setUiText(element, getText) {
  if (!element) return;
  var text = String(getText());
  uiTextBindings.set(element, { getText: getText, rendered: text });
  element.textContent = text;
}

function applyUiTranslations(root) {
  if (!root || root.nodeType !== 1) return;
  var selector = '[data-i18n],[data-i18n-placeholder],[data-i18n-title],[data-i18n-aria-label]';
  var nodes = Array.from(root.querySelectorAll(selector));
  if (root.matches(selector)) nodes.unshift(root);
  nodes.forEach(function(element) {
    if (element.hasAttribute('data-i18n')) {
      var value = t(element.getAttribute('data-i18n'));
      if (element.textContent !== value) element.textContent = value;
    }
    ['placeholder', 'title', 'aria-label'].forEach(function(attr) {
      if (!element.hasAttribute('data-i18n-' + attr)) return;
      var value = t(element.getAttribute('data-i18n-' + attr));
      if (element.getAttribute(attr) !== value) element.setAttribute(attr, value);
    });
  });
}

function setLanguage(language) {
  if (language !== 'ja' && language !== 'en') return;
  uiLanguage = language;
  document.documentElement.lang = language;
  try { localStorage.setItem('pt_language', language); } catch (e) {}
  document.querySelectorAll('[data-language-select]').forEach(function(select) {
    select.value = language;
  });
  uiTextBindings.forEach(function(binding, element) {
    // A later plain assignment may have cleared or replaced a message.
    if (!element.isConnected || element.textContent !== binding.rendered) {
      uiTextBindings.delete(element);
      return;
    }
    binding.rendered = String(binding.getText());
    element.textContent = binding.rendered;
  });
  applyUiTranslations(document.documentElement);
  // Rerender only gallery chrome; never translate users' titles or comments.
  if (typeof renderGallery === 'function' && typeof curUser !== 'undefined' && (curUser || (typeof guestMode!=='undefined' && guestMode))) renderGallery();
  if (typeof updateNavBadge === 'function' && typeof aiMode !== 'undefined') updateNavBadge();
  applyUiTranslations(document.documentElement);
}

document.documentElement.lang = uiLanguage;
document.addEventListener('DOMContentLoaded', function() {
  document.querySelectorAll('[data-language-select]').forEach(function(select) {
    select.value = uiLanguage;
    select.addEventListener('change', function() { setLanguage(select.value); });
  });
  applyUiTranslations(document.documentElement);
  // Marked labels in dynamic menus/comments are translated as they are added.
  new MutationObserver(function(records) {
    records.forEach(function(record) {
      record.addedNodes.forEach(function(node) { applyUiTranslations(node); });
    });
  }).observe(document.body, {childList: true, subtree: true});
});
